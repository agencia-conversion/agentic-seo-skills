export type Messages = typeof messages.en;
export type TranslationKey = string;

export const LOCALE_OPTIONS: { value: LocalePreference; labelKey: TranslationKey }[] = [
  { value: 'system', labelKey: 'common.system' },
  { value: 'en', labelKey: 'locale.en' },
  { value: 'pt-BR', labelKey: 'locale.pt-BR' },
];

export function getLocaleOptions(uiLocale: SupportedLocale) {
  return LOCALE_OPTIONS.map((option) => ({
    value: option.value,
    label: translate(uiLocale, option.labelKey),
  }));
}

function getPathValue(source: Record<string, any>, key: string): string | undefined {
  return key.split('.').reduce<any>((acc, part) => (acc == null ? undefined : acc[part]), source);
}

export function interpolate(message: string, vars?: Record<string, string | number>): string {
  if (!vars) return message;
  return message.replace(/\{(\w+)\}/g, (_, token) => String(vars[token] ?? `{${token}}`));
}

export function translate(
  locale: SupportedLocale,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  const value =
    getPathValue(messages[locale], key) ??
    getPathValue(messages.en, key) ??
    key;
  return interpolate(value, vars);
}

export function resolveLocale(input?: string | null): SupportedLocale | null {
  if (!input) return null;
  const normalized = input.toLowerCase();
  if (normalized.startsWith('pt')) return 'pt-BR';
  if (normalized.startsWith('en')) return 'en';
  return null;
}

export function resolvePreferredLocale(inputs: readonly string[] = []): SupportedLocale {
  for (const input of inputs) {
    const match = resolveLocale(input);
    if (match) return match;
  }
  return 'en';
}

export function localeDisplayName(locale: SupportedLocale, uiLocale: SupportedLocale): string {
  return translate(uiLocale, (`locale.${locale}` as TranslationKey));
}

export function formatDateForLocale(
  locale: SupportedLocale,
  value: number | Date,
  options?: Intl.DateTimeFormatOptions
): string {
  return new Intl.DateTimeFormat(locale, options).format(value);
}

export function formatNumberForLocale(
  locale: SupportedLocale,
  value: number | string | null | undefined,
  options?: Intl.NumberFormatOptions
): string {
  if (value == null || value === '') return '—';
  const num = typeof value === 'number' ? value : Number(value);
  if (!Number.isFinite(num)) return String(value);
  return new Intl.NumberFormat(locale, { maximumFractionDigits: 2, ...options }).format(num);
}

export function formatPercentForLocale(
  locale: SupportedLocale,
  value: number | string | null | undefined,
  options?: Intl.NumberFormatOptions
): string {
  if (value == null || value === '') return '—';
  const num = typeof value === 'number' ? value : Number(value);
  if (!Number.isFinite(num)) return String(value);
  // Value is on the 0..100 scale (matches sov_pct / ctr_uplift_modeled_pct).
  return new Intl.NumberFormat(locale, {
    style: 'percent',
    maximumFractionDigits: 1,
    ...options,
  }).format(num / 100);
}
